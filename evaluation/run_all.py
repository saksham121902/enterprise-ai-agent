async def run_evaluation_suite() -> dict:
    """Run all benchmarks and return consolidated metrics."""
    import os

    has_api_key = bool(
        os.getenv("OPENAI_API_KEY")
        or os.getenv("ANTHROPIC_API_KEY")
        or os.getenv("GEMINI_API_KEY")
    )
    eval_mode = "LIVE_LLM" if has_api_key else "OFFLINE_DETERMINISTIC"

    print("=" * 72)
    print("🚀 ENTERPRISE AI OPERATIONS AGENT — HARDENED BENCHMARK SUITE")
    print("=" * 72)
    print(f"Timestamp: {datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')}")
    print(f"Execution Mode: [{eval_mode}]")
    if not has_api_key:
        print("ℹ️  Note: No LLM API key detected in environment. Evaluator using deterministic")
        print("   token-overlap retrieval and ground-truth verification baseline.")
        print("   To execute with live LLM calls: export OPENAI_API_KEY=sk-...\n")
    else:
        print("✨ Live LLM API key detected. Answers will be generated by the real provider.\n")

    t_start = time.perf_counter()

    # 1. RAG Evaluation (48 test cases, including 8 adversarial / unanswerable)
    print("▶ [1/4] Running Hardened RAG Benchmark (48 test cases across seeded documents)...")
    rag_evaluator = RAGEvaluator()
    rag_results = await rag_evaluator.run()
    print(f"  ✓ Hit-Rate @3: {rag_results['hit_rate_at_3']}% | "
          f"Citation Accuracy: {rag_results['citation_accuracy']}% | "
          f"Avg Phrase Recall: {rag_results['avg_phrase_recall']}%")

    # 2. Text-to-SQL & Guardrail Evaluation (36 test cases, including 6 adversarial injections)
    print("\n▶ [2/4] Running Text-to-SQL & Safety Guardrail Benchmark (36 test cases)...")
    sql_evaluator = SQLEvaluator()
    sql_results = sql_evaluator.run()
    print(f"  ✓ Overall Accuracy: {sql_results['overall_accuracy']}% | "
          f"Destructive Query Block Rate: {sql_results['destructive_block_rate']}% | "
          f"Approval Routing Rate: {sql_results['approval_routing_rate']}%")

    # 3. Supervisor Routing Evaluation (26 test cases, including 6 ambiguous multi-intent)
    print("\n▶ [3/4] Running Hardened Supervisor Intent Routing Benchmark (26 test cases)...")
    routing_evaluator = RoutingEvaluator()
    routing_results = await routing_evaluator.run()
    print(f"  ✓ Routing Accuracy: {routing_results['routing_accuracy']}% ({routing_results['correct_routes']}/{routing_results['total_test_cases']} correct)")

    # 4. Latency & Cost Profiling
    print("\n▶ [4/4] Profiling Latency (p50/p95) and Query Costs across Agent Nodes...")
    profiler = LatencyProfiler()
    latency_results = await profiler.run(iterations_per_node=25)
    e2e = latency_results["profiles"]["full_pipeline_e2e"]
    print(f"  ✓ E2E Pipeline Latency: p50={e2e['p50_ms']}ms | p95={e2e['p95_ms']}ms | "
          f"Avg Cost: ${e2e['avg_cost_usd']}/query")

    total_duration = time.perf_counter() - t_start

    consolidated = {
        "metadata": {
            "timestamp": datetime.datetime.now(datetime.timezone.utc).isoformat(),
            "total_benchmark_duration_seconds": round(total_duration, 2),
            "version": "1.0.0",
            "evaluation_mode": eval_mode,
            "has_live_llm_key": has_api_key,
            "adversarial_cases_included": 20,
        },
        "rag": rag_results,
        "sql": sql_results,
        "routing": routing_results,
        "latency_and_cost": latency_results,
    }

    # Save JSON report
    output_json_path = repo_root / "evaluation" / "results.json"
    with open(output_json_path, "w", encoding="utf-8") as f:
        json.dump(consolidated, f, indent=2)
    print(f"\n📁 Raw metrics saved to: {output_json_path.relative_to(repo_root)}")

    # Generate Markdown report
    markdown_report = generate_markdown_report(consolidated)
    output_md_path = repo_root / "EVALUATION.md"
    with open(output_md_path, "w", encoding="utf-8") as f:
        f.write(markdown_report)
    print(f"📁 Markdown report generated at: {output_md_path.relative_to(repo_root)}")

    print("\n" + "=" * 72)
    print("✅ HARDENED EVALUATION SUITE COMPLETED SUCCESSFULLY")
    print("=" * 72)

    return consolidated


