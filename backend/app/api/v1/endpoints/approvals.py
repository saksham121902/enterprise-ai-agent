"""Human approval management API endpoints.

Provides listing and status management for approval requests
generated by the AI agent when it needs authorization for
sensitive operations.
"""

from __future__ import annotations

import uuid

from fastapi import APIRouter, Depends
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.api.deps import get_current_user, get_db
from app.core.exceptions import NotFoundError, ValidationError
from app.models.operational import Approval
from app.schemas.auth import MessageResponse

router = APIRouter()


@router.get(
    "/",
    summary="List approval requests",
)
async def list_approvals(
    status: str | None = None,
    user: dict = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
) -> list[dict]:
    """List approval requests for the current tenant.

    Optionally filter by status: pending, approved, rejected.
    """
    tenant_id = uuid.UUID(user.get("tenant_id", ""))

    query = (
        select(Approval)
        .where(Approval.tenant_id == tenant_id)
        .order_by(Approval.created_at.desc())
        .limit(50)
    )

    if status:
        query = query.where(Approval.status == status)

    result = await db.execute(query)
    approvals = result.scalars().all()

    return [
        {
            "id": str(a.id),
            "operation_type": a.operation_type,
            "status": a.status,
            "description": a.description,
            "payload_json": a.payload_json,
            "reviewer_notes": a.reviewer_notes,
            "requested_by": str(a.requested_by),
            "reviewed_by": str(a.reviewed_by) if a.reviewed_by else None,
            "created_at": a.created_at.isoformat(),
            "updated_at": a.updated_at.isoformat(),
        }
        for a in approvals
    ]


@router.post(
    "/{approval_id}/approve",
    response_model=MessageResponse,
    summary="Approve a request",
)
async def approve_request(
    approval_id: uuid.UUID,
    body: dict | None = None,
    user: dict = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
) -> MessageResponse:
    """Approve a pending approval request."""
    tenant_id = uuid.UUID(user.get("tenant_id", ""))
    reviewer_id = uuid.UUID(user["sub"])

    result = await db.execute(
        select(Approval).where(
            Approval.id == approval_id,
            Approval.tenant_id == tenant_id,
        )
    )
    approval = result.scalar_one_or_none()

    if not approval:
        raise NotFoundError("Approval", str(approval_id))

    if approval.status != "pending":
        raise ValidationError(
            message=f"Approval is already {approval.status}",
        )

    approval.status = "approved"
    approval.reviewed_by = reviewer_id
    approval.reviewer_notes = (body or {}).get("notes")

    return MessageResponse(message="Request approved")


@router.post(
    "/{approval_id}/reject",
    response_model=MessageResponse,
    summary="Reject a request",
)
async def reject_request(
    approval_id: uuid.UUID,
    body: dict | None = None,
    user: dict = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
) -> MessageResponse:
    """Reject a pending approval request."""
    tenant_id = uuid.UUID(user.get("tenant_id", ""))
    reviewer_id = uuid.UUID(user["sub"])

    result = await db.execute(
        select(Approval).where(
            Approval.id == approval_id,
            Approval.tenant_id == tenant_id,
        )
    )
    approval = result.scalar_one_or_none()

    if not approval:
        raise NotFoundError("Approval", str(approval_id))

    if approval.status != "pending":
        raise ValidationError(
            message=f"Approval is already {approval.status}",
        )

    approval.status = "rejected"
    approval.reviewed_by = reviewer_id
    approval.reviewer_notes = (body or {}).get("notes")

    return MessageResponse(message="Request rejected")
